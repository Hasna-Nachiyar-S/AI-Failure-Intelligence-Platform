from backend.ml.domain_model_manager import (
    DomainModelManager
)

class Recommender:

    def __init__(self, model_dir="models"):

        self.manager = DomainModelManager(
            model_dir
        )

    # Main recommendation method

    def recommend(self, data):
        domain = self.manager.normalize_domain(data.get("Domain"))
        prediction = self.manager.predict(domain, data)
        failure_type = prediction["failure_type"]
        probabilities = prediction["class_probabilities"]

        return {
            "domain": domain,
            "prediction": {
                "failure_type": failure_type,
                "probability": prediction["probability"],
                "class_probabilities": probabilities,
            },
            "probability": probabilities,
            "cluster": {"cluster": "Domain-specific"},
            "historical_analysis": {
                "domain": domain,
                "failure_types": {failure_type: 1},
                "message": "Prediction generated by the domain-specific ML model.",
            },
            "similar_failures": [],
            "recommendations": self._recommend(domain, data, failure_type),
            "improvement_actions": self._actions(domain, data, failure_type),
        }

    # Safe numeric conversion

    @staticmethod
    @staticmethod
    def _safe_float(value, default=0.0):
        try:
            return default if value is None else float(value)
        except (TypeError, ValueError):
            return default

    # Recommendations

    def _recommend(self, domain, data, failure_type):
        number = lambda key: self._safe_float(data.get(key))

        if domain == "Student":
            actions = []
            if number("absences") > 10:
                actions.append("Reduce avoidable absences.")
            if number("studytime") < 3:
                actions.append("Increase study time.")
            if number("failures") > 0:
                actions.append("Address previous academic failures.")
            if number("G2") < 10:
                actions.append("Improve academic performance.")
            if failure_type == "Passed":
                actions.append("Maintain the current study routine.")
            return actions or ["Maintain current performance."]

        if domain == "Software":
            return [
                "Investigate the reported issue.",
                "Review technical dependencies.",
                "Review issue priority.",
                "Document the root cause.",
                "Monitor the issue after resolution.",
            ]

        if domain == "Jobs":
            skills = number("skills_match_score")
            actions = [
                "Improve skills relevant to the target role."
                if skills < 50 else
                "Strengthen the current skill match."
                if skills < 70 else
                "Maintain the current skill level."
            ]
            if number("years_experience") < 2:
                actions.append("Gain additional relevant experience.")
            actions.append("Strengthen the resume with measurable achievements.")
            return actions

        if domain == "Projects":
            completion = number("Completion")
            if completion < 30:
                return [
                    "Review project schedule.",
                    "Identify blocked tasks.",
                    "Improve resource allocation.",
                    "Monitor project progress closely.",
                ]
            if completion < 60:
                return [
                    "Increase project progress.",
                    "Address delayed activities.",
                    "Review remaining project tasks.",
                ]
            return [
                "Maintain project progress.",
                "Monitor remaining activities.",
                "Address risks early.",
            ]

        return ["Review the factors affecting the prediction."]

    # Improvement actions

    def _actions(self, domain, data, failure_type):
        actions = {
            "Student": [
                "Improve academic performance",
                "Increase study time",
                "Reduce avoidable absences",
                "Review previous weak areas",
            ],
            "Software": [
                "Investigate root cause",
                "Review dependencies",
                "Fix the reported issue",
                "Monitor after resolution",
            ],
            "Jobs": [
                "Improve skill match",
                "Strengthen resume",
                "Build relevant experience",
                "Review skill gaps",
            ],
            "Projects": [
                "Monitor completion",
                "Address delayed tasks",
                "Improve planning",
                "Review project risks",
            ],
        }
        return actions.get(domain, ["Review important performance factors."])
